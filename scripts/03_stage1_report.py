"""1단계 결과 요약 문서 생성. 02_carbon_intensity.py 산출물만 읽어 숫자를 채운다.

사용법:  python scripts/03_stage1_report.py   ->  03_분석/summary_stage1.md
"""
from __future__ import annotations

import json
import sys

import pandas as pd

from common import COMPARE_YEAR, MAIN_YEAR, OUT

Y1, Y0 = str(MAIN_YEAR), str(COMPARE_YEAR)


def pct(x, d=1):
    return f"{x * 100:.{d}f}%"


def main():
    s = json.loads((OUT / "ci_summary.json").read_text(encoding="utf-8"))
    M, D, T = s["metrics"], s["daily"], s["top"]
    sens = pd.read_csv(OUT / "sensitivity_assumed_factors.csv")
    solar_path = OUT / "solar_sensitivity.json"
    solar = json.loads(solar_path.read_text(encoding="utf-8")) if solar_path.exists() else None
    log = (OUT / "logs" / "02_carbon_intensity.log").read_text(encoding="utf-8").strip().splitlines()

    L = ["# 1단계 결과: 한국 전력의 시간별 탄소집약도", "",
         "`scripts/03_stage1_report.py`가 `03_분석/`의 산출물로 자동 생성한 문서다. 직접 고치지 말고 스크립트를 다시 돌린다.", "",
         f"- 주 분석 {Y1}년, 비교·검증 {Y0}년 (2024년판은 원자력·석탄·LNG가 없어 제외)",
         "- 탄소집약도 = Σ(연료원별 거래량 × 생애주기 배출계수) / Σ거래량, 단위 gCO2eq/kWh",
         "- 시각은 구간 시작 기준. 예) '12시' = 12~13시 (원본 거래시간 13)",
         "- 6시간 지표: 하루 24개 시각 중 가장 깨끗한 6개 시각 평균과 가장 더러운 6개 시각 평균을 비교",
         "- 절감률 = 1 - 깨끗한 시간 평균 / 더러운 시간 평균. '같은 작업을 옮기면 배출이 몇 % 줄어드는가'와 같은 뜻", "",
         "## 처리 로그", ""] + [f"- {x}" for x in log] + [""]

    # 1. 연평균 곡선
    L += ["## 1. 하루 24시간 평균 곡선 (그림 fig1)", "",
          "| 지표 | " + f"{Y1}년 | {Y0}년 |", "|---|---|---|"]
    a, b = M[Y1]["연간"], M[Y0]["연간"]
    rows = [("시간 단순 평균 (gCO2eq/kWh)", "평균", "{:.1f}"), ("가장 깨끗한 시각", "최소시각", "{:.0f}시"),
            ("그때 값", "최소", "{:.1f}"), ("가장 더러운 시각", "최대시각", "{:.0f}시"), ("그때 값", "최대", "{:.1f}"),
            ("최대/최소 비율", "최대/최소", "{:.3f}"), ("최대-최소 차이", "최대-최소", "{:.1f}"),
            ("깨끗한 6시간 평균", "깨끗6h평균", "{:.1f}"), ("더러운 6시간 평균", "더러운6h평균", "{:.1f}"),
            ("더러운 6h / 깨끗한 6h 비율", "더러운6h/깨끗6h", "{:.3f}")]
    for name, k, f in rows:
        L.append(f"| {name} | {f.format(a[k])} | {f.format(b[k])} |")
    L.append(f"| **절감률: 더러운 6h → 깨끗한 6h** | **{pct(a['절감률_더러운6h→깨끗6h'])}** | **{pct(b['절감률_더러운6h→깨끗6h'])}** |")
    L.append(f"| 절감률: 하루 평균 → 깨끗한 6h | {pct(a['절감률_하루평균→깨끗6h'])} | {pct(b['절감률_하루평균→깨끗6h'])} |")
    L.append(f"| 절감률: 연속 6시간 구간끼리 | {pct(a['절감률_연속6h'])} ({a['연속6h_최고시작']:.0f}시~ → {a['연속6h_최저시작']:.0f}시~) "
             f"| {pct(b['절감률_연속6h'])} ({b['연속6h_최고시작']:.0f}시~ → {b['연속6h_최저시작']:.0f}시~) |")
    L.append("")
    L.append("가장 깨끗한 시각 / 가장 더러운 시각 상위 5개 (연평균 곡선, gCO2eq/kWh):")
    L.append("")
    for y in (Y1, Y0):
        c = ", ".join(f"{h}시 {v}" for h, v in T[y]["깨끗한 시각(연평균 곡선)"])
        d = ", ".join(f"{h}시 {v}" for h, v in T[y]["더러운 시각(연평균 곡선)"])
        L.append(f"- {y}년 깨끗: {c}")
        L.append(f"- {y}년 더러움: {d}")
    for y in (Y1, Y0):
        c = ", ".join(f"{d} {h}시 {v}" for d, h, v in T[y]["가장 깨끗한 개별 시간"])
        d = ", ".join(f"{dd} {h}시 {v}" for dd, h, v in T[y]["가장 더러운 개별 시간"])
        L.append(f"- {y}년 개별 시간 최저 5개: {c}")
        L.append(f"- {y}년 개별 시간 최고 5개: {d}")
    L.append("")

    # 2. 날짜별 분포
    L += ["## 2. 날짜별 하루 안 변동폭 분포 (그림 fig4)", "",
          f"| 지표 | {Y1}년 | {Y0}년 |", "|---|---|---|"]
    for k, f in [("최대/최소 중앙값", "{:.3f}"), ("최대/최소 25%", "{:.3f}"), ("최대/최소 75%", "{:.3f}"),
                 ("최대-최소 중앙값", "{:.1f}"), ("절감률_6h 중앙값(%)", "{:.1f}%"), ("절감률_6h 25%(%)", "{:.1f}%"),
                 ("절감률_6h 75%(%)", "{:.1f}%"), ("절감률_6h 10% 이상 일수 비율(%)", "{:.1f}%")]:
        L.append(f"| {k.replace('(%)', '')} | {f.format(D[Y1][k])} | {f.format(D[Y0][k])} |")
    L.append("")

    # 3. 계절, 요일
    L += ["## 3. 계절별, 평일/주말 차이 (그림 fig2, fig3, fig5)", "",
          "평균 곡선 기준 지표. '날짜별 중앙값'은 각 날짜 안에서 6시간 절감률을 구한 뒤 중앙값을 낸 것.", "",
          f"| 구분 | {Y1} 평균 | {Y1} 최대/최소 | {Y1} 6h 절감률 | {Y1} 날짜별 중앙값 | {Y0} 평균 | {Y0} 최대/최소 | {Y0} 6h 절감률 | {Y0} 날짜별 중앙값 |",
          "|---|---|---|---|---|---|---|---|---|"]
    for g, dk in [("봄", "계절별"), ("여름", "계절별"), ("가을", "계절별"), ("겨울", "계절별"),
                  ("평일", "요일유형별"), ("주말·공휴일", "요일유형별")]:
        cells = []
        for y in (Y1, Y0):
            m = M[y][g]
            cells += [f"{m['평균']:.1f}", f"{m['최대/최소']:.3f}", pct(m["절감률_더러운6h→깨끗6h"]),
                      f"{D[y][dk + ' 절감률_6h 중앙값(%)'][g]:.1f}%"]
        L.append(f"| {g} | " + " | ".join(cells) + " |")
    L.append("")
    L.append("평일 작업을 주말·공휴일로 미루는 경우(평균 곡선 기준):")
    L.append("")
    for y in (Y1, Y0):
        w = M[y]["평일→주말"]
        L.append(f"- {y}년: 평일 더러운 6시간 평균 {w['평일 더러운6h평균']:.1f} → 주말·공휴일 깨끗한 6시간 평균 "
                 f"{w['주말·공휴일 깨끗6h평균']:.1f}, 절감률 {pct(w['절감률_평일더러운6h→주말깨끗6h'])} "
                 f"(평일 하루 평균 기준 {pct(w['절감률_평일평균→주말깨끗6h'])})")
    L.append("")

    # 4. 민감도
    L += [f"## 4. 가정 항목 계수 ±50% 민감도 ({Y1}년, 그림 fig6)", "",
          "'정규화곡선 최대차이'는 곡선을 각자의 평균으로 나눈 모양끼리 비교한 최대 차이다. 모양이 그대로면 0에 가깝다.", "",
          "| 케이스 | 연평균 | 최대/최소 | 6h 절감률 | 절감률 변화 | 곡선 모양 상관계수 | 정규화곡선 최대차이 | 최소/최대 시각 |",
          "|---|---|---|---|---|---|---|---|"]
    show = sens[(sens["케이스"].isin(["기준", "가정 항목 전체 -50%", "가정 항목 전체 +50%"]))
                | (sens["절감률_6h 변화(%p)"].abs() >= 0.05)]
    for r in show.itertuples(index=False):
        L.append(f"| {r[0]} | {r[1]:.1f} | {r[2]:.3f} | {r[4]:.2f}% | {r[5]:+.2f}%p | {r[6]:.3f} | {r[7]:.2f}% | {r[8]}시 / {r[9]}시 |")
    rest = sens[~sens.index.isin(show.index)]
    L.append("")
    L.append(f"나머지 {len(rest)}개 케이스(연료원별 단독 ±50%)는 6h 절감률 변화가 모두 ±0.05%p 미만이다. 전체 표: `03_분석/sensitivity_assumed_factors.csv`.")
    L.append("가스압은 계수가 0이라 ±50%를 해도 값이 변하지 않는다(비중 0.001%).")
    L.append("")

    # 5. 비계량 태양광
    L += ["## 5. 비계량 태양광", ""]
    if solar:
        L += solar["lines"]
    else:
        L.append("민감도 케이스에 쓸 공식 시간별 추정 자료를 찾지 못했다. 한계 항목 참고.")
    L.append("")

    # 6. 한계
    L += ["## 6. 한계", "",
          "1. **전력시장 밖 발전 누락.** 전력거래소 거래량에는 한전과 직접 거래하는 발전기(한전PPA)와 자가용 발전이 빠져 있다. "
          "태양광은 특히 크다. 5장 EPSIS 자료로 보면 시장 밖 태양광(한전PPA+자가용)이 시장 태양광보다 훨씬 많고(합계/시장 배수 참고), 넣으면 낮 시간 하락이 커진다. "
          "기준 결과는 시간 이동 효과를 작게 잡은 쪽(보수적)이다.",
          "2. **평균 배출계수와 한계 배출계수의 차이.** 이 분석은 그 시각에 돌던 전원 전체의 평균 탄소(평균 배출계수)를 쓴다. "
          "작업 하나를 옮겼을 때 실제로 늘거나 줄어드는 발전기(한계 발전기, 한국에서는 주로 LNG나 석탄)의 탄소와는 다를 수 있다. "
          "비유하면, 버스에 한 명이 더 타도 버스 전체 연비가 아니라 '그 한 명 때문에 더 드는 연료'가 진짜 비용인 것과 같다. "
          "한계 배출계수는 공개 데이터로 바로 구할 수 없어 범위 밖으로 둔다.",
          "3. **배출계수는 세계 문헌 중앙값.** IPCC 생애주기 중앙값은 한국 발전소의 실제 효율·연료와 다를 수 있다. "
          "IPCC 표에 없는 전원(비중은 처리 로그의 '가정 항목 거래량 비중')은 비슷한 전원 값을 빌렸고, 4장 민감도 분석에서 결과에 주는 영향이 작음을 확인했다.",
          "4. **양수·저장장치 단순화.** 충전 시점의 탄소를 따지지 않고 연간 평균을 적용했다. 실제로는 밤에 충전한 전기를 낮이나 저녁에 쓰므로 시간별 값이 조금 달라질 수 있다(4장 양수 ±50% 케이스 참고).",
          "5. **연도.** 2024년판은 원자력·석탄·LNG가 없어 쓰지 않았다. 2025년과 2023년 두 해로 경향을 확인했다.",
          "6. **수정정산.** 포털 설명대로 거래량은 수정정산으로 바뀔 수 있다.",
          ""]
    out = OUT / "summary_stage1.md"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(out)


if __name__ == "__main__":
    sys.stdout.reconfigure(encoding="utf-8")
    main()
